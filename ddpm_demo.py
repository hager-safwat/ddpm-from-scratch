"""
A denoising diffusion probabilistic model (DDPM) from scratch
=============================================================

Trains the DDPM of Ho et al. (2020) on a 2-D two-moons distribution, samples
from it, measures how close the samples are to the real data, and draws the
figure. In 2-D the whole method is visible: the forward process that turns
data into noise, the network that learns to predict that noise, and the
reverse process that turns noise back into data.

All data is synthetic. This is a mechanism demo, not a benchmark.

Usage
-----
    python ddpm_demo.py                          # full run, writes figure.png
    python ddpm_demo.py --steps 300 --no-figure  # quick smoke run
    python ddpm_demo.py --unscaled-schedule      # original betas, for comparison
"""

import argparse

import numpy as np
import torch

from ddpm import EpsilonModel, NoiseSchedule, make_two_moons, mean_nn_distance, sample, train

SEED = 0
N_POINTS = 4000
T = 200


def run_experiment(steps=15000, seed=SEED, scale_schedule=True, log_every=3000):
    """Train, sample and evaluate. Returns (metrics, data, generated, snapshots, schedule).

    Order matters for exact reproducibility: one numpy generator makes the
    data, one torch seed controls initialisation, training and sampling.
    """
    rng = np.random.default_rng(seed)
    torch.manual_seed(seed)

    data = make_two_moons(N_POINTS, rng)
    schedule = NoiseSchedule(T=T, scale_to_T=scale_schedule)
    model = EpsilonModel()
    losses = train(model, data, schedule, steps=steps, log_every=log_every)
    generated, snapshots = sample(model, schedule, N_POINTS, record_every=T // 4)

    # Reference floor: a second, independent draw of REAL data (separate
    # generator, so it does not disturb the run above). A perfect generator
    # would score about the same as this real-vs-real distance.
    real_again = make_two_moons(N_POINTS, np.random.default_rng(seed + 1)).numpy()
    real, gen = data.numpy(), generated.numpy()

    metrics = {
        "final_alpha_bar": float(schedule.alphas_cumprod[-1]),
        "loss_last_1000_mean": float(np.mean(losses[-1000:])),
        "gen_to_real": mean_nn_distance(gen, real),
        "real_to_gen": mean_nn_distance(real, gen),
        "real_to_real": mean_nn_distance(real_again, real),
        "real_std": real.std(0).tolist(),
        "gen_std": gen.std(0).tolist(),
        "gen_mean": gen.mean(0).tolist(),
    }
    return metrics, data, generated, snapshots, schedule


def print_metrics(m):
    print(f"\nfinal alpha_bar_T                     {m['final_alpha_bar']:.2e}")
    print(f"training loss (mean of last 1000)      {m['loss_last_1000_mean']:.4f}")
    print("\nMean nearest-neighbour distance (standardised units, lower is better)")
    print(f"  generated -> real   (precision)      {m['gen_to_real']:.4f}")
    print(f"  real -> generated   (coverage)       {m['real_to_gen']:.4f}")
    print(f"  real -> real, fresh draw (floor)     {m['real_to_real']:.4f}")
    print("\nSpread per axis (std)")
    print(f"  real                                 {m['real_std'][0]:.3f}  {m['real_std'][1]:.3f}")
    print(f"  generated                            {m['gen_std'][0]:.3f}  {m['gen_std'][1]:.3f}")


def save_figure(data, generated, snapshots, path="figure.png"):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig = plt.figure(figsize=(13.5, 4.6))
    ax0 = fig.add_subplot(1, 3, 1)
    ax0.scatter(*data.numpy().T, s=4, alpha=0.4, color="#1f4e79")
    ax0.set_title("Target distribution\n(real two-moons data)")

    ax1 = fig.add_subplot(1, 3, 2)
    ax1.scatter(*generated.numpy().T, s=4, alpha=0.4, color="#b5651d")
    ax1.set_title("Generated by the DDPM\n(starting from pure noise)")

    ax2 = fig.add_subplot(1, 3, 3)
    snaps = sorted(snapshots, key=lambda s: -s[0])      # high t (noise) first
    cmap = plt.cm.viridis
    for i, (t, pts) in enumerate(snaps):
        ax2.scatter(*pts.numpy().T, s=3, alpha=0.35,
                    color=cmap(i / max(1, len(snaps) - 1)), label=f"t={t}")
    ax2.set_title("Reverse process\n(noise -> data, dark to light)")
    ax2.legend(fontsize=7, markerscale=2, loc="upper right", framealpha=0.9)

    for a in (ax0, ax1, ax2):
        a.set_xlim(-2.5, 2.5)
        a.set_ylim(-2.5, 2.5)
        a.set_xticks([])
        a.set_yticks([])
        a.set_aspect("equal")

    fig.suptitle("A DDPM trained from scratch learns to turn Gaussian noise into "
                 "the target two-moons distribution.", fontsize=10.5)
    fig.tight_layout(rect=[0, 0, 1, 0.93])
    fig.savefig(path, dpi=130)
    print(f"\nSaved {path}")


def main(argv=None):
    parser = argparse.ArgumentParser(description="Train and sample a 2-D DDPM.")
    parser.add_argument("--steps", type=int, default=15000, help="training steps")
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--unscaled-schedule", action="store_true",
                        help="use the original betas without the 1000/T rescaling")
    parser.add_argument("--no-figure", action="store_true", help="skip figure.png")
    args = parser.parse_args(argv)

    metrics, data, generated, snapshots, _ = run_experiment(
        steps=args.steps, seed=args.seed, scale_schedule=not args.unscaled_schedule,
        log_every=max(1, args.steps // 5),
    )
    print_metrics(metrics)
    if not args.no_figure:
        save_figure(data, generated, snapshots)
    return metrics


if __name__ == "__main__":
    main()
